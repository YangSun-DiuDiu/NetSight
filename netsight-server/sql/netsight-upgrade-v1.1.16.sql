-- 增量 SQL v1.1.16
-- 说明：device 表新增 warranty_expire（保修截止日期）字段，用于设备保修期管理
-- 派生状态（后端计算，不落库）：null=未设置 / 未过期=在保 / 已过期=已过保
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 设备表新增保修截止日期字段（DATE，可空；空=未设置保修期）
-- ---------------------------------------------------------------------
ALTER TABLE `device` ADD COLUMN `warranty_expire` DATE NULL COMMENT '保修截止日期' AFTER `collect_port`;

-- ---------------------------------------------------------------------
-- 2. 校验
-- ---------------------------------------------------------------------
SHOW COLUMNS FROM `device` LIKE 'warranty_expire';
SELECT device_code, device_name, warranty_expire FROM device WHERE del_flag = 0 ORDER BY id DESC LIMIT 5;
